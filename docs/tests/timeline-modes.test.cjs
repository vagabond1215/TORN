"use strict";
const fs=require("node:fs"),path=require("node:path"),assert=require("node:assert/strict");
const read=name=>fs.readFileSync(path.join(__dirname,"..",name),"utf8");
const sc=new Function("tornGuideApi","localStorage",read("activity-scheduler.js")+"\nreturn tornActivityScheduler;")({state:{identity:{id:1}}},{getItem:()=>null});
const H=3600000,D=24*H,M=60000,day=Date.UTC(2026,10,26),now=day+13*H+42*M+27000;
const today=sc.timelineWindow(now,"today"),two=sc.timelineWindow(now,"twoDays"),rolling=sc.timelineWindow(now,"rolling");
assert.equal(today.start,day);assert.equal(today.end,day+D);assert.equal(today.at,day+13*H+42*M);
assert.equal(two.start,day);assert.equal(two.end,day+2*D);assert.equal(two.width,1440);
assert.equal(rolling.start,today.at);assert.equal(rolling.end,rolling.start+D);
assert.equal(sc.timelineWindow(now+M,"rolling").start,rolling.start+M);
assert.equal(sc.timelineWindow(now+M,"today").start,day);
assert.equal(sc.timelineWindow(day+D-1,"twoDays").start,day);
assert.equal(sc.timelineWindow(day+D,"twoDays").start,day+D);
assert.equal(sc.timelineWindow(day+D,"today").end,day+2*D);
const event=(id,start,end=start,extra={})=>({id,kind:"training",title:id,start,end,source:"Forecast",...extra});
const rows=[event("past",day+H),event("cross-midnight",day-2*H,day+2*H),event("now",rolling.start),event("tomorrow",day+D),event("right-edge",rolling.end),event("dose",day+16*H,day+16*H,{drugCooldownSeconds:8*3600})];
const get=(layout,id)=>layout.spans.find(x=>x.event.id===id)??layout.annotations.flatMap(x=>x.items).find(x=>x.event.id===id);
const t=sc.timelineLayout(rows,now,1,null,4*3600,today);
assert.ok(get(t,"past"));assert.ok(get(t,"cross-midnight").clippedStart);assert.ok(!get(t,"tomorrow"));
const twoLayout=sc.timelineLayout(rows,now,2,null,4*3600,two);assert.ok(get(twoLayout,"tomorrow"));
const roll=sc.timelineLayout(rows,now,1,null,4*3600,rolling),roll2=sc.timelineLayout(rows,now,1,null,4*3600,sc.timelineWindow(now+M,"rolling"));
assert.ok(!get(roll,"past"));assert.ok(get(roll,"now"));assert.ok(!get(roll,"right-edge"));assert.ok(!get(roll2,"now"));
const cd=get(roll,"timeline-drug-current"),cd2=get(roll2,"timeline-drug-current");
assert.equal(cd.event.end,now+4*H);assert.equal(cd2.event.end,cd.event.end);
assert.equal(get(roll,"timeline-drug-dose").event.end,get(roll2,"timeline-drug-dose").event.end);
assert.ok(cd2.right<cd.right);assert.ok(get(roll2,"timeline-drug-dose").left<get(roll,"timeline-drug-dose").left);
const html=sc.renderModeTimeline(rows,now,null,4*3600,"home",now);
assert.ok(html.includes('data-activity-mode-timeline="home"')&&html.includes('data-activity-timeline-mode="today" aria-pressed="true"'));
assert.ok(html.includes(">2 Days</button>")&&html.includes(">24hrs</button>"));
assert.ok(html.includes("2026-11-26 00:00")&&html.includes("2026-11-27 00:00"));
assert.ok(!html.includes("activity-timeline-agenda"));
assert.ok(sc.renderModeTimeline(rows,now,null,null,"calendar",now).includes("activity-timeline-agenda"));
assert.ok(read("guide.js").includes("tornActivityScheduler.tickTimeline()"));
assert.ok(read("crime-guide.js").includes('tornActivityScheduler.renderModeTimeline(events,training.now'));
