"use strict";
// Run from repository root: node docs/tests/activity-scheduler.test.cjs
const fs=require("node:fs"),path=require("node:path"),assert=require("node:assert/strict");
const source=fs.readFileSync(path.join(__dirname,"../activity-scheduler.js"),"utf8");
const storage=new Map(),api={state:{identity:{id:1}}},store={getItem:k=>storage.get(k)??null,setItem:(k,v)=>storage.set(k,v),removeItem:k=>storage.delete(k)};
const scheduler=new Function("tornGuideApi","localStorage",source+"\nreturn tornActivityScheduler;")(api,store);
const H=3600000,now=Date.UTC(2026,10,26),ws={mode:"scheduled",adjustment:60,lead:120};
const war=scheduler.warWindow({start:now+48*H,end:now+72*H},ws,now);
assert.equal(war.cutoff,now+14*H);
assert.equal(war.clear,now+46*H);
assert.equal(war.phase,"upcoming");
assert.equal(scheduler.warWindow(war,ws,war.cutoff).phase,"stacking");
assert.equal(scheduler.warWindow(war,ws,war.start).phase,"active");
assert.equal(scheduler.warWindow(war,ws,war.end),null);
assert.equal(scheduler.limits({war,manual:[],now}).deadline,war.cutoff);
assert.equal(scheduler.limits({war,manual:[],now:war.cutoff}).blocked,true);
assert.equal(scheduler.limits({manual:[],now}).blocked,false);
assert.equal(scheduler.conflicts([{step:{type:"xanax"},done:false,due:war.cutoff-7*H}],war.cutoff,now),true);
assert.equal(scheduler.conflicts([{step:{type:"train"},done:false,due:war.cutoff-H}],war.cutoff,now),false);
assert.equal(scheduler.conflicts([{step:{type:"xanax"},done:true,due:war.cutoff+H}],war.cutoff,now),false);
const health=scheduler.addiction(true,["Battle stats reduced by 3% due to addiction"],scheduler.settings(),war);
assert.equal(health.penalty,3);
assert.equal(health.level,"recommended");
assert.equal(scheduler.addiction(false,[],scheduler.settings()).penalty,null);
assert.equal(scheduler.addiction(true,["Addiction penalty unknown"],scheduler.settings()).penalty,null);
assert.equal(scheduler.addiction(true,["Reduced by 5% due to addiction"],scheduler.settings()).blockDrugs,true);
const rehab=scheduler.rehabWindow({now,health,war,manual:[],actions:[now,now+8*H],travelAvailable:true,drugReady:now+8*H});
assert.ok(rehab&&rehab.start>now&&rehab.end<now+8*H);
assert.equal(rehab.overlapsCooldown,true);
assert.equal(scheduler.rehabWindow({now,health,war:{...war,phase:"stacking"},travelAvailable:true}),null);
assert.equal(scheduler.rehabWindow({now,health,war:{...war,cutoff:now+H},travelAvailable:true}),null);
assert.equal(scheduler.rehabWindow({now,health,travelAvailable:false}),null);
assert.ok(scheduler.saveEvent({id:"chain",kind:"chain",title:"Chain",start:now+2*H,end:now+3*H,blocking:true}));
assert.equal(scheduler.limits({war,now}).deadline,now+2*H);
assert.ok(scheduler.removeEvent("chain"));
const reserved=scheduler.budget(1000000,{...scheduler.settings(),sharedBudget:true,warReserve:800000,rehabReserve:500000},war,health);
assert.equal(reserved.training,0);assert.equal(reserved.shortfall,true);
const list=scheduler.schedule({now,war,rehab,manual:[],training:[{id:"t",kind:"training",title:"Train",start:now+H,end:now+H}],limit:war.cutoff});
assert.ok(list.some(e=>e.id==="war-cutoff"));
assert.ok(list.some(e=>e.id==="rehab-proposal"));
for(const view of ["agenda","timeline","week","month"])assert.ok(scheduler.render(list,{now,full:true,view}).includes("activity-calendar"));
console.log("Activity scheduler regression checks passed.");
