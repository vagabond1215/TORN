"use strict";
const assert=require("node:assert/strict"),records=require("../log-records.js"),c=require("../log-coverage.js");
const now=Date.UTC(2026,10,27),r=(id,at=now)=>({id,timestamp:at/1000,details:{id:1,category:"Fixture",title:"Event"},data:{},params:{}});
const p=(rows,ns,at=now,player=1)=>records.decodePage({log:rows,_metadata:{links:{prev:ns===null?null:"opaque link not followed",next:null},...(ns===null||ns===undefined?{}:{nanostamp:ns})}},player,at);
const accept=(s,page)=>{const t=c.task(s,page.observedAt),result=c.apply(s,t,page);assert.equal(result.ok,true);return result.checkpoint;};
let s=c.create("1");
s=accept(s,p([r("a"),r("b")],"9000000000000000009"));
assert.equal(s.head.id,"a");assert.equal(s.older,"9000000000000000009");
s=accept(s,p([r("c",now-1000)],"9000000000000000008",now+60000));
assert.equal(s.olderTail.id,"c");
const headTime=now+300000;
s=accept(s,p([r("new",now+1000),r("b")],"8888888888888888888",headTime));
assert.equal(s.pending.target.id,"a"); // b is not the head anchor; cannot certify coverage
assert.equal(s.head.id,"a");assert.equal(s.headCheckedAt,now);
assert.equal(c.task(s,headTime+600000).kind,"catchup");
s=accept(s,p([r("a")],"8888888888888888887",headTime+60000));
assert.equal(s.pending,null);assert.equal(s.head.id,"new");assert.equal(s.headCheckedAt,headTime);
assert.equal(s.older,"9000000000000000008");
const oldTask=c.task(s,headTime+61000);
assert.equal(c.apply(s,{...oldTask,revision:0},p([],null,headTime+61000)).ok,false);
assert.equal(c.apply(s,oldTask,p([],null,headTime+61000,2)).ok,false);
s=accept(s,p([],null,headTime+61000));assert.equal(s.olderState,"terminal");assert.equal(s.gap,null);
assert.equal(c.task(s,headTime+62000),null);
let gap=accept(c.create("1"),p([r("a")],undefined));assert.ok(gap.gap);assert.equal(c.task(gap,now+600000),null);
let cycle=accept(c.create("1"),p([r("a")],"10"));
cycle=accept(cycle,p([r("b")],"9",now+60000));
cycle=accept(cycle,p([r("c")],"10",now+120000));assert.ok(cycle.gap);
let missing=accept(c.create("1"),p([r("a")],"10"));
missing=accept(missing,p([r("x",now+1000),r("y",now-1000)],"20",now+300000));assert.ok(missing.gap);
let order=accept(c.create("1"),p([r("a")],"10"));
assert.equal(c.apply(order,c.task(order,now+60000),p([r("b",now+1000)],"9",now+60000)).ok,false);
let bound=accept(c.create("1"),p([r("a")],"10"));
bound={...bound,olderRecent:Array.from({length:c.MAX_CHAIN},(_,i)=>String(i+100))};
bound=accept(bound,p([r("b")],"11",now+60000));assert.ok(bound.gap);
console.log("Exact head-anchor catchup, independent older checkpoint, stale/foreign task rejection, terminal hints, missing/cyclic cursors and bounded chain tests passed.");
let boundary=accept(c.create("1"),p([r("a")],"10"));
const beforeHead=c.task(boundary,now+299000);
assert.equal(beforeHead.kind,"older");
assert.equal(c.apply(boundary,beforeHead,p([r("b",now-1000)],"9",now+301000)).ok,true);
console.log("An in-flight older page remains valid across the head refresh deadline.");
