"use strict";
// Run from repo root: node docs/tests/crime-states-and-war.test.cjs
const fs=require("node:fs"),path=require("node:path"),assert=require("node:assert/strict");
const read=n=>fs.readFileSync(path.join(__dirname,"..",n),"utf8");
const m=new Function(read("crime-states.js")+"\nreturn tornCrimeStates;")();
const map=new Map(),store={getItem:k=>map.get(k)??null,setItem:(k,v)=>map.set(k,v),removeItem:k=>map.delete(k)};
const now=Date.UTC(2026,10,26),H=3600000;
const count=crime=>m.data[crime].reduce((n,t)=>n+t[6].length,0);
assert.equal(count("Search for Cash"),34);assert.equal(count("Shoplifting"),59);
assert.equal(m.data["Search for Cash"].length,6);assert.equal(m.data.Shoplifting.length,8);
assert.ok(m.save("1",store,"Search for Cash","junkyard","meter","49",now));
assert.equal(m.observed(m.load("1",store),"Search for Cash","junkyard","meter",now).value,49);
assert.equal(m.observed(m.load("2",store),"Search for Cash","junkyard","meter",now).value,null);
assert.equal(m.observed(m.load("1",store),"Search for Cash","junkyard","meter",now+900000).expired,true);
assert.equal(m.save("1",store,"Search for Cash","junkyard","meter","101",now),false);
assert.equal(m.save("1",store,"Search for Cash","cemetery","meter","30",now),false);
assert.ok(m.save("1",store,"Shoplifting","jewelry","meter","0",now));
assert.ok(m.save("1",store,"Shoplifting","jewelry","camera","disabled",now));
assert.ok(m.save("1",store,"Shoplifting","jewelry","guard","off",now));
assert.equal(m.observed(m.load("1",store),"Shoplifting","jewelry","meter",now+300000).value,null);
assert.equal(m.observed(m.load("1",store),"Shoplifting","jewelry","camera",now+300000).value,"disabled");
assert.equal(m.observed(m.load("1",store),"Shoplifting","cyber","camera",now).value,null);
const html=m.render("Shoplifting",{cs:100,owner:"1",store,now,only:false});
assert.ok(html.includes("Cluster Ring")&&html.includes("Notoriety 0% + Cameras Disabled + Guard Off duty / break")&&html.includes("Observed match"));
assert.equal((html.match(/class="crime-state-target"/g)||[]).length,8);
const search=m.render("Search for Cash",{cs:100,owner:"1",store,now,uniques:[{rewards:{items:[{name:"Mountain Bike",quantity:1}]}}]});
assert.ok(!search.includes(">Mountain Bike<")&&search.includes("33 reference outcomes shown"));
assert.equal(m.collected("Search for Cash",[{rewards:{items:[{name:"Mountain Bike"}]}}],[]).size,0);
assert.equal(m.collected("Search for Cash",[{rewards:{items:[{name:"Mountain Bike",quantity:2}]}}],[]).size,0);
assert.equal(m.collected("Search for Cash",[{rewards:{items:[{id:77,quantity:1}]}}],[{id:77,name:"Mountain Bike"}]).size,1);
assert.ok(m.render("Search for Cash",{owner:"1",store,now,allCollected:true}).includes("0 reference outcomes shown"));
assert.ok(m.save("1",store,"Shoplifting","jewelry","meter","",now));
assert.equal(m.observed(m.load("1",store),"Shoplifting","jewelry","meter",now).value,null);
assert.equal(m.conditionMatch([["camera","eq","disabled"],["guard","eq","off"]],k=>k==="camera"?"disabled":null),"unknown");
assert.equal(m.conditionMatch([["meter","range",[0,49]]],()=>50),"mismatch");
const s=new Function("tornGuideApi","localStorage",read("activity-scheduler.js")+"\nreturn tornActivityScheduler;")({state:{identity:{id:1}}},store);
const war=s.warWindow({start:now+34*H,end:now+72*H},{mode:"scheduled",adjustment:60,lead:120},now);
for(const energy of [0,250,500,750,790,1000]){
 const p=s.warPreparation(war,{energy,drug:0},4,false,now);
 assert.equal(p.doses.length,Math.ceil((1000-energy)/250));
 assert.equal(p.projectedEnergy,1000);
 assert.ok(p.doses.every(d=>d.at+war.cd<=war.start));
 const rows=s.schedule({now,war,preparation:p,manual:[]}).filter(e=>e.id.startsWith("war-dose-"));
 assert.equal(rows.length,p.doses.length);
 assert.ok(rows.every((e,i)=>e.start===p.doses[i].at));
}
assert.equal(s.warPreparation(war,null,4,false,now).doses.length,0);
assert.equal(s.warPreparation(war,{energy:750,drug:0},null,false,now).doses.length,0);
assert.equal(s.warPreparation(war,{energy:500,drug:0},1,false,now).doses.length,1);
assert.equal(s.warPreparation(war,{energy:500,drug:0},4,true,now).doses.length,0);
assert.equal(s.warPreparation(war,{energy:0,drug:0},4,false,now+H).bufferReduced,true);
assert.equal(s.warPreparation(war,{energy:0,drug:0},4,false,now+3*H).doses.length,3);
assert.equal(s.warPreparation(war,{energy:0,drug:0},4,false,war.start).phase,"active");
assert.equal(s.warPreparation(war,{energy:0,drug:0},4,false,now-H).tentative,true);
assert.equal(s.warPreparation(war,{energy:750,drug:9*3600},4,false,now+24*H).doses.length,0);
console.log("Crime references, observation isolation/expiry, collection matches, war schedule parity and boundary cases passed.");
